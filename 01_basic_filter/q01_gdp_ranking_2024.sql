-- ============================================================
-- Q01 · 2024 年各省 GDP 排行
-- ============================================================
-- 业务场景：给领导做一页「去年谁最能打」，按经济体量排序。
--
-- 考点：WHERE 过滤 + ORDER BY 排序
-- 预期结果：11 行 × 2 列，第一行广东（141633.8）
--
-- 思路：
--   1. WHERE 年份 = 2024 锁定当年
--   2. ORDER BY GDP_亿元 DESC 降序
-- ============================================================

SELECT "省份", "GDP_亿元"
FROM panel_hqd
WHERE "年份" = 2024
ORDER BY "GDP_亿元" DESC;
