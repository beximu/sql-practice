-- ============================================================
-- Q02 · 辽宁十年人均 GDP 走势
-- ============================================================
-- 业务场景：领导问「辽宁这十年人均 GDP 是怎么走的」。
--
-- 考点：按字符串条件筛省份 + 时间序列排序
-- 预期结果：10 行 × 2 列，2015 → 2024
--
-- 思路：
--   1. 省份写法是 '辽宁' 不是 '辽宁省'，多一个字就查不到
--   2. 时间序列默认升序，不用写 ASC
-- ============================================================

SELECT "年份", "人均GDP_元"
FROM panel_hqd
WHERE "省份" = '辽宁'
ORDER BY "年份";
