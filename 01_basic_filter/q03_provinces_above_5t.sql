-- ============================================================
-- Q03 · 2024 年 GDP 超 5 万亿的省
-- ============================================================
-- 业务场景：筛出「万亿俱乐部」里的头部省份。
--
-- 考点：多条件 AND + 数值阈值 + 单位换算
-- 预期结果：6 行 × 2 列
--
-- 思路：
--   1. 5 万亿 = 50000 亿元，表里单位是亿元，别写成 5
--   2. 题目是「超过」，用 > 而不是 >=
-- ============================================================

SELECT "省份", "GDP_亿元"
FROM panel_hqd
WHERE "年份" = 2024
  AND "GDP_亿元" > 50000
ORDER BY "GDP_亿元" DESC;
