-- ============================================================
-- Q04 · 2024 年人均 GDP 前三
-- ============================================================
-- 业务场景：找「最富裕的三个省」。
--
-- 考点：TOP N：ORDER BY + LIMIT
-- 预期结果：3 行 × 2 列，第一是上海（约 21.7 万）
--
-- 思路：
--   1. Top N 问题 = ORDER BY 降序 + LIMIT N
--   2. LIMIT 在所有排序之后生效，所以必须配合 ORDER BY
-- ============================================================

SELECT "省份", "人均GDP_元"
FROM panel_hqd
WHERE "年份" = 2024
ORDER BY "人均GDP_元" DESC
LIMIT 3;
