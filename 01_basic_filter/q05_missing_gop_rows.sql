-- ============================================================
-- Q05 · 找出海洋生产总值缺失的省份年份
-- ============================================================
-- 业务场景：项目一的结论是「海洋生产总值只有 85 个观测」，现在把它落到具体行上。
--
-- 考点：IS NULL 判断缺失（不能用 = NULL）
-- 预期结果：25 行 × 2 列（110 − 85 = 25，正好对上项目一的数字）
--
-- 思路：
--   1. 判断空值只能写 IS NULL
--   2. 写 = NULL 永远返回 0 行，而且不报错 —— 最阴的坑
--   3. 缺失行也要排好序，否则业务方没法按省份核对
-- ============================================================

SELECT "省份", "年份"
FROM panel_hqd
WHERE "海洋生产总值_亿元" IS NULL
ORDER BY "省份", "年份";
