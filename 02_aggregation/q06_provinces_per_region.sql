-- ============================================================
-- Q06 · 每个区域有几个省
-- ============================================================
-- 业务场景：三大海洋经济区各自的省份数量。
--
-- 考点：GROUP BY + COUNT(DISTINCT)
-- 预期结果：3 行 × 2 列（4 / 4 / 3，加起来 11）
--
-- 思路：
--   1. 一个省有 10 行（10 年），COUNT(*) 会得到 40
--   2. 要数省份个数，必须 COUNT(DISTINCT 省份)
-- ============================================================

SELECT "区域", COUNT(DISTINCT "省份") AS "省份数"
FROM panel_hqd
GROUP BY "区域"
ORDER BY "省份数" DESC;
