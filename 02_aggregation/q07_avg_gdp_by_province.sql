-- ============================================================
-- Q07 · 各省十年平均 GDP
-- ============================================================
-- 业务场景：看哪些省的经济体量长期领先，而不是只看某一年。
--
-- 考点：GROUP BY + AVG
-- 预期结果：11 行 × 2 列
--
-- 思路：
--   1. GROUP BY 省份后，每个省压成一行
--   2. ROUND 保留 1 位小数，结果才可读
-- ============================================================

SELECT "省份", ROUND(AVG("GDP_亿元"), 1) AS "平均GDP"
FROM panel_hqd
GROUP BY "省份"
ORDER BY "平均GDP" DESC;
