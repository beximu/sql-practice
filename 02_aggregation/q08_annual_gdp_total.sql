-- ============================================================
-- Q08 · 11 省 GDP 年度合计
-- ============================================================
-- 业务场景：看沿海省份整体经济体量的十年走势。
--
-- 考点：GROUP BY 求和，看年度总量
-- 预期结果：10 行 × 2 列
--
-- 思路：
--   1. 这次分组键是年份，不是省份
--   2. SUM 会忽略 NULL，相比 COUNT(*) 更适合做加总
-- ============================================================

SELECT "年份", ROUND(SUM("GDP_亿元"), 1) AS "GDP合计"
FROM panel_hqd
GROUP BY "年份"
ORDER BY "年份";
