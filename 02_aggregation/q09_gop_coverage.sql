-- ============================================================
-- Q09 · 海洋生产总值数据覆盖够全的省
-- ============================================================
-- 业务场景：做时间序列分析前，先筛掉观测太少的省，否则趋势图会断。
--
-- 考点：COUNT(列名) + HAVING 过滤分组结果
-- 预期结果：6 行 × 2 列
--
-- 思路：
--   1. COUNT(列名) 只数非空值，COUNT(*) 会连 NULL 一起数
--   2. 筛选聚合结果（计数 ≥ 8）必须用 HAVING，不能用 WHERE
--   3. 题目要求降序 —— 覆盖最全的省排前面
-- ============================================================

SELECT "省份", COUNT("海洋生产总值_亿元") AS "有值年数"
FROM panel_hqd
GROUP BY "省份"
HAVING COUNT("海洋生产总值_亿元") >= 8
ORDER BY "有值年数" DESC;
