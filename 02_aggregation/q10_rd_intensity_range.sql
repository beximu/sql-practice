-- ============================================================
-- Q10 · 各省 R&D 投入强度的波动幅度
-- ============================================================
-- 业务场景：研发投入忽高忽低的省，数据质量或统计口径可能有问题。
--
-- 考点：同组内 MAX / MIN 与四则运算
-- 预期结果：11 行 × 4 列
--
-- 思路：
--   1. 极差 = MAX - MIN，可以在同一个 SELECT 里直接算
--   2. 聚合函数的参数不能写成嵌套聚合，但同层聚合可以互相运算
-- ============================================================

SELECT "省份",
       ROUND(MAX("RD投入强度_pct"), 2) AS "最高",
       ROUND(MIN("RD投入强度_pct"), 2) AS "最低",
       ROUND(MAX("RD投入强度_pct") - MIN("RD投入强度_pct"), 2) AS "极差"
FROM panel_hqd
GROUP BY "省份"
ORDER BY "极差" DESC;
