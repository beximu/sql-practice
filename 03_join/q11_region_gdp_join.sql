-- ============================================================
-- Q11 · 区域 GDP 合计（跨表关联）
-- ============================================================
-- 业务场景：GDP 数据在长表 macro 里，区域标签在宽表 panel_hqd 里，要拼起来。
--
-- 考点：两表 JOIN，双键关联
-- 预期结果：3 行 × 2 列
--
-- 思路：
--   1. 一个省有 10 年，只用省份关联会产生 10 倍笛卡尔积，必须加年份
--   2. 同一张表里多个指标混在「指标」列，记得 WHERE 指标 = 'GDP'
-- ============================================================

SELECT p."区域", ROUND(SUM(m."数值"), 1) AS "GDP合计"
FROM macro m
JOIN panel_hqd p
  ON m."省份" = p."省份"
 AND m."年份" = p."年份"
WHERE m."指标" = 'GDP'
  AND m."年份" = 2024
GROUP BY p."区域"
ORDER BY "GDP合计" DESC;
