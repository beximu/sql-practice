-- ============================================================
-- Q12 · 两张来源表合并后各省的记录数
-- ============================================================
-- 业务场景：GOP 主表缺了一部分，另有一张人工补齐的补丁表，要合起来看覆盖情况。
--
-- 考点：UNION ALL 纵向合并 + 子查询
-- 预期结果：11 行 × 2 列
--
-- 思路：
--   1. UNION 会去重、拖慢速度；UNION ALL 不去重，这里应该用 UNION ALL
--   2. 两个 SELECT 的列数、顺序、类型必须一致
--   3. 主表先过滤掉 NULL，否则补齐的省会被重复计数
-- ============================================================

SELECT "省份", COUNT(*) AS "条数"
FROM (
    SELECT "省份" FROM gop WHERE "数值" IS NOT NULL
    UNION ALL
    SELECT "省份" FROM gop_supplement
) t
GROUP BY "省份"
ORDER BY "条数" DESC;
