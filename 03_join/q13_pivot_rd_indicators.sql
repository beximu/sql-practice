-- ============================================================
-- Q13 · 长表转宽表：R&D 四项指标
-- ============================================================
-- 业务场景：原始数据是「一行一个指标」的长表，分析时要转成「一行一个省年」的宽表。
--
-- 考点：CASE WHEN 条件聚合，长表转宽表
-- 预期结果：110 行 × 6 列
--
-- 思路：
--   1. MAX(CASE WHEN 指标 = 'X' THEN 数值 END) 是做透视的标准写法
--   2. 为什么用 MAX 而不是 SUM：每组里每个指标只有一行，MAX 取出那个非空值
--   3. END 后面不写 ELSE，不匹配的行得到 NULL，正是我们要的
-- ============================================================

SELECT "省份",
       "年份",
       MAX(CASE WHEN "指标" = 'R&D经费内部支出'  THEN "数值" END) AS "RD支出",
       MAX(CASE WHEN "指标" = 'R&D经费投入强度'  THEN "数值" END) AS "RD强度",
       MAX(CASE WHEN "指标" = '专利授权量'        THEN "数值" END) AS "专利授权量",
       MAX(CASE WHEN "指标" = '发明专利授权量'    THEN "数值" END) AS "发明专利"
FROM tech
GROUP BY "省份", "年份"
ORDER BY "省份", "年份";
