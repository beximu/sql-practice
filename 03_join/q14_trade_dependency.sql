-- ============================================================
-- Q14 · 外贸依存度（构造派生指标）
-- ============================================================
-- 业务场景：进出口总额 ÷ GDP，衡量一个省的经济对外依赖程度。
--
-- 考点：JOIN 后做除法，构造派生指标
-- 预期结果：11 行 × 4 列
--
-- 思路：
--   1. 两个数在两个表里，必须先 JOIN 到同一行才能相除
--   2. 关联条件要同时限定省份和年份，漏一个就会乘出错误的行
--   3. 先把两个子查询各自过滤到 2023 年，再 JOIN —— 比 JOIN 完再 WHERE 更省
-- ============================================================

SELECT t."省份",
       ROUND(t."数值", 2) AS "进出口",
       ROUND(m."数值", 2) AS "GDP",
       ROUND(t."数值" / m."数值" * 100, 2) AS "外贸依存度"
FROM (
    SELECT "省份", "年份", "数值"
    FROM trade
    WHERE "年份" = 2023 AND "指标" = '货物进出口总额'
) t
JOIN (
    SELECT "省份", "年份", "数值"
    FROM macro
    WHERE "年份" = 2023 AND "指标" = 'GDP'
) m
  ON t."省份" = m."省份"
 AND t."年份" = m."年份"
ORDER BY "外贸依存度" DESC;
