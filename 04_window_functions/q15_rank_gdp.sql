-- ============================================================
-- Q15 · 2024 年 GDP 排名（RANK）
-- ============================================================
-- 业务场景：给 11 个省排名，并列时名次要相同、且不跳号。
--
-- 考点：RANK() 排名
-- 预期结果：11 行 × 3 列
--
-- 思路：
--   1. RANK() 并列同名次且跳号（1,1,3）；DENSE_RANK() 并列同名次不跳号（1,1,2）
--   2. RANK() OVER (ORDER BY ...) 里的 ORDER BY 只决定排名规则，不影响输出顺序
--   3. 最终输出顺序还是要靠最外层的 ORDER BY
-- ============================================================

SELECT "省份",
       "GDP_亿元",
       RANK() OVER (ORDER BY "GDP_亿元" DESC) AS "排名"
FROM panel_hqd
WHERE "年份" = 2024
ORDER BY "排名";
