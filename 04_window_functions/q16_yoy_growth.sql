-- ============================================================
-- Q16 · 各省 GDP 同比增速（LAG）
-- ============================================================
-- 业务场景：算每一年的 GDP 增速，这是所有时间序列分析的第一步。
--
-- 考点：LAG() 取上一行，算同比
-- 预期结果：99 行 × 3 列（11 省 × 9 年，2015 年没有上一年）
--
-- 思路：
--   1. LAG(列, 1) 取上一行，PARTITION BY 省份保证不在省之间串行
--   2. 第一年 LAG 返回 NULL，除法会得到 NULL，这正是我们要的（不伪造 0）
--   3. 先在同一层把 LAG 算好，外层再相除 —— 否则要重复写两遍窗口函数
-- ============================================================

SELECT "省份",
       "年份",
       ROUND(("GDP_亿元" - last_gdp) / last_gdp * 100, 2) AS "增速"
FROM (
    SELECT "省份",
           "年份",
           "GDP_亿元",
           LAG("GDP_亿元", 1) OVER (PARTITION BY "省份" ORDER BY "年份") AS last_gdp
    FROM panel_hqd
) t
WHERE "年份" >= 2016
ORDER BY "省份", "年份";
