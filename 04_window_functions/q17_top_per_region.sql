-- ============================================================
-- Q17 · 每个区域 GDP 最高的省
-- ============================================================
-- 业务场景：「每组取第一名」—— 面试出现频率最高的窗口函数题型。
--
-- 考点：ROW_NUMBER() + PARTITION BY 取组内第一
-- 预期结果：3 行 × 3 列
--
-- 思路：
--   1. ROW_NUMBER() 一定给出唯一序号，即使并列也不会两个第 1
--   2. 窗口函数不能直接写进 WHERE（WHERE 执行时它还没算），必须套一层子查询
--   3. 题目要的是「最强的区」，所以按 GDP 降序输出
-- ============================================================

SELECT "区域", "省份", "GDP_亿元"
FROM (
    SELECT "区域",
           "省份",
           "GDP_亿元",
           ROW_NUMBER() OVER (PARTITION BY "区域" ORDER BY "GDP_亿元" DESC) AS rn
    FROM panel_hqd
    WHERE "年份" = 2024
) t
WHERE rn = 1
ORDER BY "GDP_亿元" DESC;
