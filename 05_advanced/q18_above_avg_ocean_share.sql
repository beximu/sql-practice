-- ============================================================
-- Q18 · 海洋经济占比高于平均的省
-- ============================================================
-- 业务场景：找出海洋产业对本地经济拉动最强的省，和 11 省均值比。
--
-- 考点：CTE + 子查询比较平均值
-- 预期结果：4 行 × 2 列
--
-- 思路：
--   1. CTE（WITH）先把当年有值的省筛出来，避免 NULL 拉低均值
--   2. 子查询里再算一次 AVG，用同一个 CTE，保证分子分母口径一致
--   3. 不能在 WHERE 里直接写聚合函数，但可以写只返回一个值的子查询
-- ============================================================

WITH ocean AS (
    SELECT "省份",
           ROUND("海洋生产总值占GDP比重_pct", 2) AS "比重"
    FROM panel_hqd
    WHERE "年份" = 2024
      AND "海洋生产总值占GDP比重_pct" IS NOT NULL
)
SELECT "省份", "比重"
FROM ocean
WHERE "比重" > (SELECT AVG("比重") FROM ocean)
ORDER BY "比重" DESC;
