-- ============================================================
-- Q19 · 2024 增速 vs 本省十年平均增速
-- ============================================================
-- 业务场景：判断一个省今年是「超常发挥」还是「回归常态」，要跟自己的历史比。
--
-- 考点：窗口函数 + 聚合 JOIN，对比个体与自身均值
-- 预期结果：11 行 × 3 列
--
-- 思路：
--   1. 两件事要分两步：① 逐行算增速（窗口函数）② 按省算平均增速（聚合）
--   2. 先聚合再 JOIN，比先 JOIN 再 GROUP BY 快得多，也不容易写错
--   3. LAG 只在子查询里算一次，外层直接引用 —— 避免重复写两遍窗口函数
-- ============================================================

WITH growth AS (
    SELECT "省份",
           "年份",
           ("GDP_亿元" - LAG("GDP_亿元", 1) OVER (PARTITION BY "省份" ORDER BY "年份"))
           / LAG("GDP_亿元", 1) OVER (PARTITION BY "省份" ORDER BY "年份") * 100 AS "增速"
    FROM panel_hqd
),
avg_growth AS (
    SELECT "省份", AVG("增速") AS "平均增速"
    FROM growth
    WHERE "增速" IS NOT NULL
    GROUP BY "省份"
)
SELECT g."省份",
       ROUND(g."增速", 2)     AS "增速2024",
       ROUND(a."平均增速", 2) AS "平均增速"
FROM growth g
JOIN avg_growth a ON g."省份" = a."省份"
WHERE g."年份" = 2024
ORDER BY "增速2024";
