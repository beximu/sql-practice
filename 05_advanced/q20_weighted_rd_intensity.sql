-- ============================================================
-- Q20 · 区域加权 R&D 投入强度
-- ============================================================
-- 业务场景：整体研发强度不能把各省强度简单平均，要按 GDP 加权。
--
-- 考点：加权平均：先求和再相除，不是 AVG
-- 预期结果：3 行 × 2 列
--
-- 思路：
--   1. 加权平均 = Σ(分子) / Σ(分母)，不是 AVG(强度)
--   2. 简单平均会让小省和大省权重相同，结论会失真 —— 这是面试常考点
--   3. 先 GROUP BY 求两个汇总，再在同一层相除
-- ============================================================

WITH region_sum AS (
    SELECT "区域",
           SUM("RD经费内部支出_亿元") AS sum_rd,
           SUM("GDP_亿元")            AS sum_gdp
    FROM panel_hqd
    WHERE "年份" = 2024
    GROUP BY "区域"
)
SELECT "区域",
       ROUND(sum_rd / sum_gdp * 100, 2) AS "加权RD强度"
FROM region_sum
ORDER BY "加权RD强度" DESC;
